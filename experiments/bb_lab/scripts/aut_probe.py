"""Size the Aut-extension lever for shard_distance transport.

For each code: enumerate Aut(G), keep the φ that map {supp A, supp B}
to a common-shift image (plain: A→A, B→B; swap: A→B, B→A composed with
the block swap), build the explicit qubit permutation, and accept it
only if it maps the row set of H_X and H_Z to themselves (verified by
exact row matching — the same numeric soundness gate the translations
use, no algebra trusted). Then recount class orbits under the group
generated by translations + accepted maps.

Output per code: #plain, #swap automorphisms; orbit count before/after.
This decides whether implementing extended transport in shard_distance
is worth it (the payoff is fewer selector pins and larger stabilizers).

Usage:  uv run python scripts/aut_probe.py
"""

from __future__ import annotations

import time
from pathlib import Path

import numpy as np
import yaml

LAB_ROOT = Path(__file__).resolve().parent.parent

from bb_lab.automorphism import automorphisms  # noqa: E402
from bb_lab.checks import bb_check_matrices  # noqa: E402
from bb_lab.group import ZmZn  # noqa: E402
from bb_lab.poly import Poly  # noqa: E402
from bb_lab.shard_distance import (  # noqa: E402
    _bits_to_int,
    _int_to_bits,
    compute_class_action,
)


def _row_index(H: np.ndarray) -> dict[bytes, int]:
    idx: dict[bytes, int] = {}
    for i, row in enumerate(H):
        b = row.tobytes()
        if b in idx:
            return {}  # duplicate rows: row-matching ambiguous, skip code
    idx = {row.tobytes(): i for i, row in enumerate(H)}
    return idx


def _accept_perm(perm: np.ndarray, mats: list[np.ndarray],
                 row_idx: list[dict[bytes, int]]) -> bool:
    """True iff column-permuting each H by `perm` permutes its rows."""
    for H, idx in zip(mats, row_idx):
        for row in H:
            if row[perm].tobytes() not in idx:
                return False
    return True


def probe(name: str, ell: int, m: int, a: str, b: str) -> None:
    G = ZmZn(ell, m)
    A = Poly.from_string(a, G)
    B = Poly.from_string(b, G)
    checks = bb_check_matrices(A, B)
    action = compute_class_action(checks)
    k = action.k
    N = G.cardinality
    elems = list(G)
    eidx = {g: i for i, g in enumerate(elems)}

    mats = [checks.H_X, checks.H_Z]
    row_idx = [_row_index(H) for H in mats]
    if not all(row_idx):
        print(f"{name}: duplicate check rows — probe skipped")
        return

    t0 = time.time()
    auts = automorphisms(G)

    def qubit_perm(phi, t, swap: bool) -> np.ndarray:
        """(block, h) ↦ (block xor swap, φ(h) + t)."""
        pos = np.empty(N, dtype=np.int64)
        for i, g in enumerate(elems):
            pos[i] = eidx[G.add(phi(g), t)]
        perm = np.empty(2 * N, dtype=np.int64)
        if swap:
            perm[:N] = pos + N
            perm[N:] = pos
        else:
            perm[:N] = pos
            perm[N:] = pos + N
        return perm

    accepted: list[tuple[np.ndarray, str]] = []
    n_plain = n_swap = 0
    supA, supB = A.support, B.support
    for phi in auts:
        iA = phi.apply_support(supA)
        iB = phi.apply_support(supB)
        for swap, (tgtA, tgtB) in (
            (False, (supA, supB)), (True, (supB, supA)),
        ):
            a0 = next(iter(tgtA))
            for img in iA:
                t = G.sub(img, a0)
                if (
                    frozenset(G.add(x, t) for x in tgtA) == iA
                    and frozenset(G.add(x, t) for x in tgtB) == iB
                ):
                    perm = qubit_perm(phi, t, swap)
                    if _accept_perm(perm, mats, row_idx):
                        accepted.append((perm, "swap" if swap else "plain"))
                        if swap:
                            n_swap += 1
                        else:
                            n_plain += 1
                    break  # one t per (φ, swap) suffices

    # Class maps for accepted perms; extend the translation generators.
    gen_maps: list[np.ndarray] = []
    gx = G.index(tuple([1] + [0] * (G.rank - 1)))
    gy = G.index(tuple([0] * (G.rank - 1) + [1]))
    gen_maps.append(action.rho_rows[gx])
    gen_maps.append(action.rho_rows[gy])
    n_trivial_ext = 0
    for perm, _tag in accepted:
        Vt = np.zeros_like(action.V)
        Vt[:, perm] = action.V
        R = (Vt @ action.L_Z.T % 2).astype(np.uint8)
        if np.array_equal(R, np.eye(k, dtype=np.uint8)):
            n_trivial_ext += 1
        gen_maps.append(R)

    # Orbit recount under the extended generator set (BFS).
    size = 1 << k
    seen = np.zeros(size, dtype=bool)
    orbits = 0
    for c in range(1, size):
        if seen[c]:
            continue
        orbits += 1
        stack = [c]
        seen[c] = True
        while stack:
            cur = stack.pop()
            bits = _int_to_bits(cur, k)
            for R in gen_maps:
                img = _bits_to_int((bits @ R) % 2)
                if not seen[img]:
                    seen[img] = True
                    stack.append(img)

    print(
        f"{name}: |Aut(G)|={len(auts)}  plain={n_plain}  swap={n_swap}  "
        f"(class-trivial: {n_trivial_ext})  "
        f"orbits {len(action.orbit_reps)} → {orbits}  "
        f"[{time.time() - t0:.1f}s]",
        flush=True,
    )


def main() -> None:
    table = yaml.safe_load(
        (LAB_ROOT / "instances" / "bravyi_table.yaml").read_text()
    )["instances"]
    for row in table:
        probe(
            row["code_id"],
            row["group"]["ell"], row["group"]["m"],
            row["polynomials"]["A"], row["polynomials"]["B"],
        )


if __name__ == "__main__":
    main()
