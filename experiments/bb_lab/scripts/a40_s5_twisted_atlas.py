    for name, w1s in [("x-axis (t,p)=(0,1)", (1, 0)),
                      ("y-axis-ish", (0, 1))]:
        mp, _ = poly_u([(-a, -b) for a, b in A_L], w1s)
        mq, _ = poly_u([(-a, -b) for a, b in B_L], w1s)
        gh = gcd_f2(mp, mq)
        print(f"anchor {name}: ghat weight {bin(gh).count('1')} "
              f"(monomial {bin(gh).count('1') == 1})")

    out["wall_s"] = round(time.time() - t0, 1)
    (DATA / "s5_twisted_atlas.json").write_text(json.dumps(out, indent=1))
    print(f"wrote {DATA/'s5_twisted_atlas.json'} ({out['wall_s']} s)")


