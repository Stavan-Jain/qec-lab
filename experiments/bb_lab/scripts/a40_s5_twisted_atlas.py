def poly_u(supp, w1):
    """One-variable image bitmask (int) + min exponent, F2-exact."""
    acc = {}
    for e0, e1 in supp:
        k = w1[0] * e0 + w1[1] * e1
        acc[k] = acc.get(k, 0) ^ 1
    ks = [k for k, v in acc.items() if v]
    if not ks:
        return 0, 0
    lo = min(ks)
    m = 0
    for k in ks:
        m |= 1 << (k - lo)
    return m, lo


def gcd_f2(a, b):
    """gcd of F2[u] polynomials as bitmasks."""
    while b:
        # a mod b
        db = b.bit_length() - 1
        while a and a.bit_length() - 1 >= db:
            a ^= b << (a.bit_length() - 1 - db)
        a, b = b, a
    return a


