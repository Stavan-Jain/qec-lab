def bezout(t, p):
    """(a, b) with a t + b p = gcd(t, p)."""
    r0, r1, a0, a1, b0, b1 = t, p, 1, 0, 0, 1
    while r1:
        q = r0 // r1
        r0, r1 = r1, r0 - q * r1
        a0, a1 = a1, a0 - q * a1
        b0, b1 = b1, b0 - q * b1
    return a0, b0


def transform_class(p, t):
    """Unimodular W with W (t,p)^T = (0, g)^T; returns (W rows, g)."""
    g = math.gcd(t, p)
    a, b = bezout(t, p)
    w1 = (p // g, -t // g)
    w2 = (a, b)
    det = w1[0] * w2[1] - w1[1] * w2[0]
    assert det in (1, -1)
    if det == -1:
        w2 = (-a, -b)
    assert w1[0] * t + w1[1] * p == 0
    assert w2[0] * t + w2[1] * p in (g, -g)
    return w1, w2, g


def tr_supp(supp, w1, w2, g):
    """Transport a support through the basis change (X free, Y mod g);
    F2 cancellations applied."""
    acc = {}
    for e0, e1 in supp:
        X = w1[0] * e0 + w1[1] * e1
        Y = (w2[0] * e0 + w2[1] * e1) % g
        acc[(X, Y)] = acc.get((X, Y), 0) ^ 1
    return [k for k, v in acc.items() if v]


def atlas_run(Psupp, Qsupp, g, Wcap, max_states=8_000_000,
              max_paths=400_000):
    """The S4 atlas engine on an explicit pair (verbatim BFS + DAG
    readout, embed-and-classify re-verification)."""
    au = Automaton(Psupp, Qsupp, g)
    z = au.zero()
    layers = {(z, 0): None}
    frontier = [(z, 0)]
    parents: dict = {}
    npop = 0
    while frontier:
        nxt = []
        for (st, cost) in frontier:
            npop += 1
            if npop > max_states:
                raise RuntimeError("state cap exceeded")
            budget = Wcap - cost
            for a in range(1 << g):
                if bin(a).count("1") > budget:
                    continue
                st2, c2, _ = au.step(st, a)
                cost2 = cost + c2
                if cost2 > Wcap:
                    continue
                if st2 == z and not any(st) and a == 0:
                    continue
                key = (st2, cost2)
                if key not in layers:
                    layers[key] = (st, cost, a)
                    nxt.append(key)
                parents.setdefault(key, []).append((st, cost, a))
        frontier = nxt
    out = []

    def walk_back(key, suffix):
        if len(out) > max_paths:
            raise RuntimeError("path cap exceeded")
        st, cost = key
        if st == z and cost == 0:
            out.append(tuple(reversed(suffix)))
            return
        for (pst, pcost, a) in parents.get(key, []):
            walk_back((pst, pcost), suffix + [a])

    for cost in range(1, Wcap + 1):
        if (z, cost) in layers:
            walk_back((z, cost), [])
    rows = []
    for inputs in out:
        pts, st = au.readout_cols(list(inputs)
                                  + [0] * (au.nf + au.no + 2))
        assert st == au.zero()
        cl = embed_and_classify(pts, Psupp, Qsupp, g)
        if cl is None or cl["weight"] > Wcap:
            continue
        cl["pts"] = sorted(pts)
        rows.append(cl)
    return rows, npop


def verify_on_torus(p, t, w1, w2, g, pts_XY, Psupp, Qsupp, lstar=42):
    """Map a cylinder object back to original coordinates and verify
    on the sheared torus (lstar, p, t) OF THE LANE'S OWN PAIR
    (P, Q): cycle + weight + class.  (For the BAbar lane the object
    is a cycle of the (B, Abar) code, not of (A, B).)"""
    from bb_lab.tower import TowerCode
    from a40_s4_phase_triage import snf2
    Wm = np.array([[w1[0], w1[1]], [w2[0], w2[1]]], dtype=np.int64)
    det = int(round(np.linalg.det(Wm)))
    assert det == 1
    Wi = np.array([[Wm[1, 1], -Wm[0, 1]], [-Wm[1, 0], Wm[0, 0]]],
                  dtype=np.int64)
    M = [[lstar, 0], [t, p]]
    D, U, V = snf2(M)
    o = (abs(D[0][0]), abs(D[1][1]))

    def tr(supp):
        return frozenset(((e[0] * V[0][0] + e[1] * V[1][0]) % o[0],
                          (e[0] * V[0][1] + e[1] * V[1][1]) % o[1])
                         for e in supp)

    code = TowerCode(f"tv({lstar},{p},{t})", o, tr(Psupp), tr(Qsupp))
    v = np.zeros(code.n, dtype=np.uint8)
    for (c, y, blk) in pts_XY:
        e0 = Wi[0, 0] * c + Wi[0, 1] * y
        e1 = Wi[1, 0] * c + Wi[1, 1] * y
        f = ((e0 * V[0][0] + e1 * V[1][0]) % o[0],
             (e0 * V[0][1] + e1 * V[1][1]) % o[1])
        v[blk * code.ng + code.G.index(f)] ^= 1
    w = int(v.sum())
    return dict(lstar=lstar, weight=w, is_cycle=bool(code.is_cycle(v)),
                nontrivial=bool(code.is_cycle(v)
                                and not code.is_stab(v)))


