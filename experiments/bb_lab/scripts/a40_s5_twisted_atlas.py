    P0, Q0 = PAIRS["AB"]
    rows, npop = atlas_run(tr_supp(P0, w1, w2, g),
                           tr_supp(Q0, w1, w2, g), g, 11)
    ntv = [r for r in rows if r["nontrivial"]]
    out["dual_closure_64BAbar"] = dict(
        via="(4,2) AB at Wcap 11", n_compact=len(rows),
        n_nontrivial=len(ntv),
        min_nontrivial=min([r["weight"] for r in ntv], default=None))
    print(f"\n(6,4) BAbar dual closure via (4,2) AB @ Wcap 11: "
          f"{len(rows)} compact, {len(ntv)} nontrivial "
          f"(min {out['dual_closure_64BAbar']['min_nontrivial']})",
          flush=True)

    # ---- g = 1 twist classes (the line criterion) ---------------------
    def poly_div(a, b):
        """a / b over F2[u] (exact); None if not divisible."""
        q = 0
        db = b.bit_length() - 1
        while a:
            da = a.bit_length() - 1
            if da < db:
                return None
            q |= 1 << (da - db)
            a ^= b << (da - db)
        return q

    lines = [(p, t) for p in range(2, 9) for t in range(1, p)
             if math.gcd(t, p) == 1]
    print(f"\ng = 1 (line) classes: {len(lines)}: {lines}")
