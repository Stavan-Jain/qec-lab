#!/usr/bin/env python3
"""A17 E16 — exploratory census for the w = 5 (1,k) kills.

For live class members (regenerated by a15_t42_w5_sweep.py --sat-cap 0),
enumerate the translation classes of small supports T with |B·T| = 5 =
|A| — the (1,|T|) split candidates — and classify them against the
generic classes, seeding the w = 5 analog of A16 Lemma 5.3.1.

Verified here per member:
  I1  B·B = B² with weight 5 (char-2 Frobenius; no 2-torsion in dB);
  I2  B·(−B) has weight 21 = 1 + |dB| (Sidon count; the reflection
      class is never a (1,5) candidate);
  C3  full census of 3-set classes T (0 ∈ T) with |B·T| = 5;
  C5  full census of 5-set classes T with |B·T| = 5, split into
      T ~ B + t (generic Frobenius class, image = B² + t) vs extras.

Signatures recorded per hit: |dT ∩ dB| (ordered count), the image's
difference-set overlap with dA/dB, whether the image is a translate
of A (an ACTUAL match — should be ZERO on d ≥ 10 members for C3
since a (1,3) match is a weight-4 cycle), and the collapse pattern
(multiset of cell multiplicities in the raw 15/25-cell product).

Usage (from experiments/bb_lab):
    uv run python scripts/a15_t42_w5_sweep.py --frames 7x9 --sat-cap 0 \
        --out data/a17/members_7x9.jsonl
    uv run python scripts/a17_w5_identities_probe.py \
        --in data/a17/members_7x9.jsonl --out data/a17/e16_census_7x9.jsonl
"""

from __future__ import annotations

import argparse
import itertools
import json
import sys
import time
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))

from bb_lab.group import AbelianGroup
from bb_lab.poly import Poly


def conv_support(S: tuple, T: tuple, G: AbelianGroup) -> Counter:
    """Raw cell multiplicities of the product Σ_{s,t} x^{s+t}."""
    c: Counter = Counter()
    for s in S:
        for t in T:
            c[G.add(s, t)] += 1
    return c


def f2_image(cells: Counter) -> frozenset:
    return frozenset(g for g, n in cells.items() if n % 2)


def diffset(S, G) -> Counter:
    d: Counter = Counter()
    for a in S:
        for b in S:
            if a != b:
                d[G.sub(a, b)] += 1
    return d


def is_translate(S: frozenset, T: frozenset, G: AbelianGroup) -> bool:
    if len(S) != len(T):
        return False
    t0 = next(iter(T))
    for s0 in S:
        t = G.sub(s0, t0)
        if S == frozenset(G.add(x, t) for x in T):
            return True
    return False


def probe_member(row: dict) -> dict:
    ell, m = row["frame"]
    G = AbelianGroup((ell, m))
    A = tuple(sorted(Poly.from_string(row["A"], G).support))
    B = tuple(sorted(Poly.from_string(row["B"], G).support))
    Aset, Bset = frozenset(A), frozenset(B)
    dA = diffset(A, G)
    dB = diffset(B, G)
    n = G.cardinality
    elems = [g for g in G]
    nonzero = [g for g in elems if any(g)]
    zero = tuple(0 for _ in range(G.rank))

    out = {"frame": row["frame"], "A": row["A"], "B": row["B"]}

    # I1: Frobenius square
    Bsq_cells = conv_support(B, B, G)
    Bsq = f2_image(Bsq_cells)
    out["I1_Bsq_weight"] = len(Bsq)
    assert len(Bsq) == 5, "B*B not weight 5 — 2-torsion in dB?!"

    # I2: reflection image
    negB = tuple(G.neg(b) for b in B)
    refl = f2_image(conv_support(B, negB, G))
    out["I2_refl_weight"] = len(refl)
    assert len(refl) == 21, f"B*(-B) weight {len(refl)} != 21?!"

    # C3: 3-set census (translation-normalized: 0 ∈ T)
    hits3 = []
    for t1, t2 in itertools.combinations(nonzero, 2):
        T = (zero, t1, t2)
        cells = conv_support(B, T, G)
        img = f2_image(cells)
        if len(img) != 5:
            continue
        dT = diffset(T, G)
        collapse = tuple(sorted(cells.values(), reverse=True))
        hits3.append({
            "T": [list(t) for t in T],
            "dT_in_dB": sum(1 for d in dT if d in dB),
            "collapse": collapse,
            "img_is_A_translate": is_translate(img, Aset, G),
            "img_is_Bsq_translate": is_translate(img, Bsq, G),
            "img_is_B_translate": is_translate(img, Bset, G),
        })
    out["C3_hits"] = hits3
    out["C3_count"] = len(hits3)
    out["C3_matches"] = sum(1 for h in hits3 if h["img_is_A_translate"])

    # C5: 5-set census
    hits5 = []
    n_generic = 0
    t0 = time.time()
    for rest in itertools.combinations(nonzero, 4):
        T = (zero, *rest)
        Tset = frozenset(T)
        cells = conv_support(B, T, G)
        img = f2_image(cells)
        if len(img) != 5:
            continue
        if is_translate(Tset, Bset, G):
            n_generic += 1        # T ~ B: image = B² + t, the Frobenius class
            continue
        dT = diffset(T, G)
        collapse = tuple(sorted(cells.values(), reverse=True))
        hits5.append({
            "T": [list(t) for t in T],
            "dT_in_dB": sum(1 for d in dT if d in dB),
            "collapse": collapse,
            "img_is_A_translate": is_translate(img, Aset, G),
            "img_is_Bsq_translate": is_translate(img, Bsq, G),
        })
    out["C5_generic_B_translates"] = n_generic
    out["C5_extra_hits"] = hits5
    out["C5_extra_count"] = len(hits5)
    out["C5_matches"] = sum(1 for h in hits5 if h["img_is_A_translate"])
    out["C5_secs"] = round(time.time() - t0, 1)
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--in", dest="inp", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--limit", type=int, default=None)
    args = ap.parse_args()

    members = []
    with open(args.inp) as f:
        for line in f:
            r = json.loads(line)
            if "A" in r:
                members.append(r)
    if args.limit:
        members = members[: args.limit]
    print(f"{len(members)} members from {args.inp}", flush=True)

    outp = Path(args.out)
    outp.parent.mkdir(parents=True, exist_ok=True)
    agg3: Counter = Counter()
    agg5: Counter = Counter()
    total_matches = 0
    with outp.open("w") as out:
        for i, row in enumerate(members, 1):
            res = probe_member(row)
            out.write(json.dumps(res) + "\n")
            out.flush()
            for h in res["C3_hits"]:
                agg3[(h["dT_in_dB"], h["collapse"])] += 1
            for h in res["C5_extra_hits"]:
                agg5[(h["dT_in_dB"], h["collapse"])] += 1
            total_matches += res["C3_matches"] + res["C5_matches"]
            print(json.dumps({
                "member": i, "C3": res["C3_count"],
                "C3_matches": res["C3_matches"],
                "C5_generic": res["C5_generic_B_translates"],
                "C5_extra": res["C5_extra_count"],
                "C5_matches": res["C5_matches"],
                "secs": res["C5_secs"],
            }), flush=True)

    print("\n(1,3) class signatures (dT∩dB, collapse) -> count:")
    for k, v in sorted(agg3.items()):
        print(f"  {k}: {v}")
    print("(1,5) EXTRA class signatures:")
    for k, v in sorted(agg5.items()):
        print(f"  {k}: {v}")
    print(f"TOTAL actual matches (should be 0 on d>=10 members): "
          f"{total_matches}")


if __name__ == "__main__":
    main()
